create or replace function public.fn_create_donation(p_amount bigint)
returns table(order_ref text, amount bigint)
language plpgsql security definer set search_path to 'public','pg_temp' as $function$
#variable_conflict use_column
declare v_no bigint;
begin
 if p_amount is null or p_amount < 1000 or p_amount > 10000000 then raise exception 'BAD_AMOUNT'; end if;
 if (select count(*) from public.donations d where d.status='pending' and d.created_at > now() - interval '1 minute') >= 30 then
   raise exception 'TOO_MANY_REQUESTS';
 end if;
 insert into public.donations(amount, user_id) values (p_amount, auth.uid())
 returning donations.order_no into v_no;
 return query select 'D'||v_no, p_amount;
end; $function$;
revoke all on function public.fn_create_donation(bigint) from public;
grant execute on function public.fn_create_donation(bigint) to anon, authenticated;

create or replace function public.fn_donation_prepare(p_order_no bigint, p_trans_id text, p_amount numeric, p_payload jsonb default null)
returns table(code int, note text, prepare_id bigint)
language plpgsql security definer set search_path to 'public','pg_temp' as $function$
#variable_conflict use_column
declare v public.donations%rowtype;
begin
 select * into v from public.donations d where d.order_no=p_order_no for update;
 if not found then return query select -5, 'User does not exist'::text, null::bigint; return; end if;
 if v.status='paid' then return query select -4, 'Already paid'::text, v.order_no; return; end if;
 if v.status<>'pending' then return query select -9, 'Transaction cancelled'::text, v.order_no; return; end if;
 if p_amount is null or round(p_amount,2)<>v.amount::numeric then
   return query select -2, 'Incorrect parameter amount'::text, v.order_no; return; end if;
 update public.donations set provider_trans_id=p_trans_id, provider_state=1, raw_payload=coalesce(p_payload, raw_payload) where id=v.id;
 return query select 0, 'Success'::text, v.order_no;
end; $function$;

create or replace function public.fn_donation_complete(p_order_no bigint, p_prepare_id bigint, p_trans_id text,
  p_amount numeric, p_provider_error int, p_payload jsonb default null)
returns table(code int, note text, confirm_id bigint)
language plpgsql security definer set search_path to 'public','pg_temp' as $function$
#variable_conflict use_column
declare v public.donations%rowtype;
begin
 select * into v from public.donations d where d.order_no=p_order_no for update;
 if not found or p_prepare_id is distinct from v.order_no or v.provider_trans_id is distinct from p_trans_id then
   return query select -6, 'Transaction does not exist'::text, null::bigint; return; end if;
 if v.status='paid' then return query select -4, 'Already paid'::text, v.order_no; return; end if;
 if v.status<>'pending' then return query select -9, 'Transaction cancelled'::text, v.order_no; return; end if;
 if coalesce(p_provider_error,0) < 0 then
   update public.donations set status='failed', provider_state=-1, raw_payload=coalesce(p_payload, raw_payload) where id=v.id;
   return query select -9, 'Transaction cancelled'::text, v.order_no; return; end if;
 if p_amount is null or round(p_amount,2)<>v.amount::numeric then
   return query select -2, 'Incorrect parameter amount'::text, v.order_no; return; end if;
 update public.donations set status='paid', provider_state=2, paid_at=now(), raw_payload=coalesce(p_payload, raw_payload) where id=v.id;
 return query select 0, 'Success'::text, v.order_no;
end; $function$;

revoke all on function public.fn_donation_prepare(bigint, text, numeric, jsonb) from public, anon, authenticated;
revoke all on function public.fn_donation_complete(bigint, bigint, text, numeric, int, jsonb) from public, anon, authenticated;
grant execute on function public.fn_donation_prepare(bigint, text, numeric, jsonb) to service_role;
grant execute on function public.fn_donation_complete(bigint, bigint, text, numeric, int, jsonb) to service_role;
