-- Kirish shart emas. Donat hech qanday kirish huquqi bermaydi.

create table if not exists public.donations(
  id               uuid primary key default gen_random_uuid(),
  order_no         bigint generated by default as identity unique,
  amount           bigint not null check (amount between 1000 and 10000000),
  status           text not null default 'pending' check (status in ('pending','paid','failed','rejected')),
  user_id          uuid references public.profiles(id) on delete set null,
  provider_trans_id text,
  provider_state   int,
  raw_payload      jsonb,
  created_at       timestamptz not null default now(),
  paid_at          timestamptz
);
comment on table public.donations is 'Ixtiyoriy donatlar (Click). Yozish faqat RPC orqali; oʻqish faqat admin.';
create unique index if not exists uq_donations_provider_trans on public.donations(provider_trans_id) where provider_trans_id is not null;
alter table public.donations enable row level security;
revoke all on public.donations from anon, authenticated;
grant select on public.donations to authenticated;
drop policy if exists "donations: admin oʻqiydi" on public.donations;
create policy "donations: admin oʻqiydi" on public.donations for select to authenticated using (public.fn_is_admin());

