-- ---------- Modulga kirish: oylikda faza boʻyicha, qolganida avvalgidek ----------
create or replace function public.kompas_my_module_access(p_course_slug text, p_module_index integer)
returns boolean language plpgsql stable security definer set search_path to 'public','pg_temp' as $function$
declare v_mod uuid; v_en public.enrollments%rowtype;
begin
 if not public.kompas_account_active() then return false; end if;
 select m.id into v_mod from public.modules m join public.courses c on c.id=m.course_id
 where c.slug=p_course_slug and m.order_index=p_module_index;
 if v_mod is null then return false; end if;
 if public.kompas_module_permitted(v_mod) then return true; end if;
 select e.* into v_en from public.enrollments e join public.modules m on m.course_id=e.course_id
 where e.user_id=auth.uid() and m.id=v_mod;
 if not found or v_en.payment_status not in ('paid','partial') or v_en.frozen_at is not null
    or (v_en.expires_at is not null and v_en.expires_at<=now()) then
   return false;
 end if;
 if v_en.plan::text = 'monthly' then
   return exists (select 1 from public.course_phases p
     where p.course_slug=p_course_slug and p.phase<=coalesce(v_en.phase,0)
       and (p.track='' or p.track=coalesce(v_en.track,''))
       and p_module_index = any(p.module_indexes));
 end if;
 return v_en.unlocked_modules is null or public.fn_module_position(v_mod)<=v_en.unlocked_modules;
end; $function$;

-- ---------- Buyurtma yaratish (talaba "Toʻlash" ni bosganda) ----------
drop function if exists public.fn_create_pending_payment(text, public.payment_method);
create or replace function public.fn_create_pending_payment(p_course_slug text, p_plan text, p_track text default null)
returns table(order_no bigint, amount bigint, course_title text, plan text, phase int, track text, phase_modules int[])
language plpgsql security definer set search_path to 'public','pg_temp' as $function$
#variable_conflict use_column
declare
 v_user uuid := auth.uid(); v_c public.courses%rowtype; v_e public.enrollments%rowtype;
 v_has boolean; v_active boolean; v_amount bigint; v_phase int; v_track text; v_max int; v_no bigint; v_mods int[];
begin
 if v_user is null then raise exception 'AUTH_REQUIRED' using errcode='28000'; end if;
 if not public.kompas_account_active() then raise exception 'ACCOUNT_SUSPENDED'; end if;
 if p_plan is null or p_plan not in ('monthly','6m','yearly') then raise exception 'BAD_PLAN'; end if;

 select * into v_c from public.courses where slug=p_course_slug;
 if not found then raise exception 'COURSE_NOT_FOUND'; end if;
 if v_c.slug='test-lab' then
   if not public.fn_is_admin() then raise exception 'COURSE_NOT_FOR_SALE'; end if;
 elsif not exists (select 1 from public.paid_pages where course_slug=v_c.slug) then
   raise exception 'COURSE_NOT_FOR_SALE';
 end if;

 v_amount := case p_plan when 'monthly' then v_c.price_monthly when '6m' then v_c.price_6m
                         else coalesce(v_c.price_yearly, v_c.price) end;
 if v_amount is null or v_amount < 1000 then raise exception 'PLAN_NOT_AVAILABLE'; end if;

 select * into v_e from public.enrollments where user_id=v_user and course_id=v_c.id;
 v_has := found;
 v_active := v_has and v_e.payment_status in ('paid','partial') and v_e.frozen_at is null
             and (v_e.expires_at is null or v_e.expires_at>now());
 if v_active and v_e.installment_id is not null and v_e.payment_status<>'paid' then
   raise exception 'INSTALLMENT_ACTIVE';
 end if;
 if v_active and v_e.expires_at is null then raise exception 'ALREADY_ENROLLED'; end if;

 if p_plan='monthly' then
   if v_active and v_e.plan::text in ('6m','yearly') then raise exception 'HAS_FULL_PLAN'; end if;
   select max(cp.phase) into v_max from public.course_phases cp where cp.course_slug=v_c.slug;
   if v_max is null then raise exception 'MONTHLY_NOT_AVAILABLE'; end if;
   v_phase := case when v_has and v_e.plan::text='monthly' then coalesce(v_e.phase,0)+1 else 1 end;
   if v_phase > v_max then raise exception 'ALL_PHASES_PAID'; end if;
   v_track := case when v_has then v_e.track end;
   if exists (select 1 from public.course_phases cp where cp.course_slug=v_c.slug and cp.phase=v_phase and cp.track<>'') then
     v_track := coalesce(v_track, lower(nullif(trim(p_track),'')));
     if v_track is null or not exists (select 1 from public.course_phases cp
          where cp.course_slug=v_c.slug and cp.phase=v_phase and cp.track=v_track) then
       raise exception 'TRACK_REQUIRED';
     end if;
   end if;
   select coalesce(array_agg(x order by x), '{}') into v_mods
     from public.course_phases cp, unnest(cp.module_indexes) x
    where cp.course_slug=v_c.slug and cp.phase=v_phase and (cp.track='' or cp.track=coalesce(v_track,''));
 end if;

 -- Click hali tekshirmagan eski buyurtmalar bekor (ikki marta toʻlovning oldini olish)
 update public.payments p set status='rejected', note=concat_ws('; ', p.note, 'yangi buyurtma bilan almashtirildi')
  where p.user_id=v_user and p.course_id=v_c.id and p.status='pending'
    and p.installment_item_id is null and p.provider_trans_id is null;

 insert into public.payments(user_id, course_id, plan, amount, method, status, phase, track)
 values (v_user, v_c.id, p_plan::public.enrollment_plan, v_amount, 'click', 'pending', v_phase, v_track)
 returning payments.order_no into v_no;

 return query select v_no, v_amount, v_c.title, p_plan, v_phase, v_track, v_mods;
end; $function$;
revoke all on function public.fn_create_pending_payment(text, text, text) from public, anon;
grant execute on function public.fn_create_pending_payment(text, text, text) to authenticated;

-- ---------- Click Prepare (faqat server / service_role) ----------
create or replace function public.fn_payment_prepare(p_order_no bigint, p_method public.payment_method,
  p_trans_id text, p_amount numeric, p_payload jsonb default null)
returns table(code int, note text, prepare_id bigint)
language plpgsql security definer set search_path to 'public','pg_temp' as $function$
#variable_conflict use_column
declare v_p public.payments%rowtype; v_e public.enrollments%rowtype; v_has boolean; v_active boolean; v_expect int;
begin
 select * into v_p from public.payments where payments.order_no=p_order_no for update;
 if not found or v_p.method<>p_method or v_p.installment_item_id is not null then
   return query select -5, 'User does not exist'::text, null::bigint; return; end if;
 if v_p.status='paid' then return query select -4, 'Already paid'::text, v_p.order_no; return; end if;
 if v_p.status<>'pending' then return query select -9, 'Transaction cancelled'::text, v_p.order_no; return; end if;
 if p_amount is null or round(p_amount,2)<>v_p.amount::numeric then
   return query select -2, 'Incorrect parameter amount'::text, v_p.order_no; return; end if;

 select * into v_e from public.enrollments where user_id=v_p.user_id and course_id=v_p.course_id;
 v_has := found;
 v_active := v_has and v_e.payment_status in ('paid','partial') and v_e.frozen_at is null
             and (v_e.expires_at is null or v_e.expires_at>now());
 if v_active and v_e.expires_at is null then
   return query select -9, 'Transaction cancelled'::text, v_p.order_no; return; end if;
 if v_p.plan::text='monthly' then
   if v_active and v_e.plan::text in ('6m','yearly') then
     return query select -9, 'Transaction cancelled'::text, v_p.order_no; return; end if;
   v_expect := case when v_has and v_e.plan::text='monthly' then coalesce(v_e.phase,0)+1 else 1 end;
   if v_p.phase is distinct from v_expect then
     update public.payments set status='rejected', note=concat_ws('; ', note, 'eskirgan buyurtma (faza)') where id=v_p.id;
     return query select -9, 'Transaction cancelled'::text, v_p.order_no; return; end if;
 end if;

 update public.payments set provider_trans_id=p_trans_id, provider_prepare_id=v_p.order_no::text, provider_state=1,
   provider_create_time=coalesce(provider_create_time,(extract(epoch from now())*1000)::bigint),
   raw_payload=coalesce(p_payload, raw_payload)
 where id=v_p.id;
 return query select 0, 'Success'::text, v_p.order_no;
end; $function$;

-- ---------- Click Complete (faqat server / service_role) ----------
create or replace function public.fn_payment_complete(p_order_no bigint, p_prepare_id bigint, p_method public.payment_method,
  p_trans_id text, p_amount numeric, p_provider_error int, p_payload jsonb default null)
returns table(code int, note text, confirm_id bigint)
language plpgsql security definer set search_path to 'public','pg_temp' as $function$
#variable_conflict use_column
declare v_p public.payments%rowtype;
begin
 select * into v_p from public.payments where payments.order_no=p_order_no for update;
 if not found or v_p.method<>p_method or p_prepare_id is distinct from v_p.order_no
    or v_p.provider_trans_id is distinct from p_trans_id then
   return query select -6, 'Transaction does not exist'::text, null::bigint; return; end if;
 if v_p.status='paid' then return query select -4, 'Already paid'::text, v_p.order_no; return; end if;
 if v_p.status<>'pending' then return query select -9, 'Transaction cancelled'::text, v_p.order_no; return; end if;
 if coalesce(p_provider_error,0) < 0 then
   update public.payments set status='failed', provider_state=-1,
     provider_cancel_time=(extract(epoch from now())*1000)::bigint, provider_cancel_reason=p_provider_error,
     raw_payload=coalesce(p_payload, raw_payload)
   where id=v_p.id;
   return query select -9, 'Transaction cancelled'::text, v_p.order_no; return; end if;
 if p_amount is null or round(p_amount,2)<>v_p.amount::numeric then
   return query select -2, 'Incorrect parameter amount'::text, v_p.order_no; return; end if;

 update public.payments set status='paid', provider_state=2,
   provider_perform_time=(extract(epoch from now())*1000)::bigint,
   raw_payload=coalesce(p_payload, raw_payload), confirmed_at=now(), confirmed_by=p_method::text||'_webhook'
 where id=v_p.id;  -- trg_activate_enrollment obunani ochadi
 return query select 0, 'Success'::text, v_p.order_no;
end; $function$;

revoke all on function public.fn_payment_prepare(bigint, public.payment_method, text, numeric, jsonb) from public, anon, authenticated;
revoke all on function public.fn_payment_complete(bigint, bigint, public.payment_method, text, numeric, int, jsonb) from public, anon, authenticated;
grant execute on function public.fn_payment_prepare(bigint, public.payment_method, text, numeric, jsonb) to service_role;
grant execute on function public.fn_payment_complete(bigint, bigint, public.payment_method, text, numeric, int, jsonb) to service_role;

-- ---------- Toʻlov "paid" boʻlganda obunani ochish ----------
create or replace function public.fn_activate_enrollment()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare v_e public.enrollments%rowtype; v_has boolean; v_active boolean; v_plan text; v_slug text;
  v_phase int; v_track text; v_unlocked int; v_exp timestamptz; v_base timestamptz;
begin
 if NEW.installment_item_id is not null then return NEW; end if;
 if NOT (NEW.status in ('confirmed','paid') and (TG_OP='INSERT' or OLD.status not in ('confirmed','paid'))) then
   return NEW; end if;

 v_plan := NEW.plan::text;
 select slug into v_slug from public.courses where id=NEW.course_id;
 select * into v_e from public.enrollments where user_id=NEW.user_id and course_id=NEW.course_id for update;
 v_has := found;
 v_active := v_has and v_e.payment_status in ('paid','partial') and v_e.frozen_at is null
             and (v_e.expires_at is null or v_e.expires_at>now());

 if v_plan='monthly' then
   v_track := coalesce(NEW.track, case when v_has then v_e.track end);
   v_phase := greatest(coalesce(case when v_has and v_e.plan::text='monthly' then v_e.phase end,0), coalesce(NEW.phase,1));
   select 1 + count(distinct x) into v_unlocked
     from public.course_phases cp, unnest(cp.module_indexes) x
    where cp.course_slug=v_slug and cp.phase<=v_phase and (cp.track='' or cp.track=coalesce(v_track,''));
   -- Asoschi 2026-11-06: oylikning tugamagan kunlari qoʻshilmaydi, muddat toʻlov kunidan boshlanadi
   v_exp := now() + interval '30 days';
 elsif v_plan in ('6m','yearly') then
   v_phase := null; v_track := case when v_has then v_e.track end; v_unlocked := null;
   v_base := case when v_active and v_e.plan::text in ('6m','yearly') and v_e.expires_at>now() then v_e.expires_at else now() end;
   v_exp := v_base + case when v_plan='6m' then interval '6 months' else interval '12 months' end;
 else
   -- eski 'starter' / admin qoʻlda: muddatsiz (avvalgi xatti-harakat)
   v_phase := null; v_track := null; v_unlocked := null; v_exp := null;
 end if;

 insert into public.enrollments(user_id, course_id, plan, payment_status, payment_id, enrolled_at,
                                unlocked_modules, expires_at, frozen_at, phase, track)
 values (NEW.user_id, NEW.course_id, NEW.plan, 'paid', NEW.id, now(), v_unlocked, v_exp, null, v_phase, v_track)
 on conflict (user_id, course_id) do update set
   plan=excluded.plan, payment_status='paid', payment_id=excluded.payment_id,
   enrolled_at=coalesce(public.enrollments.enrolled_at, now()),
   unlocked_modules=excluded.unlocked_modules, expires_at=excluded.expires_at, frozen_at=null,
   phase=excluded.phase, track=excluded.track, updated_at=now();
 return NEW;
end; $function$;
